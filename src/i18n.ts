export function setLanguage(language: Language) {
  currentLanguage = language;
}

export function language(): Language {
  return currentLanguage;
}

export function translate(text: string): string {
  if (currentLanguage === 'en') return text;
  const exact = POLISH[text];
  if (exact !== undefined) return exact;

  const targeting = text.match(/^Cast (.+): (tap a target, or Cancel|pick a target \(Esc to cancel\))$/);
  if (targeting) {
    const verb = targeting[2].startsWith('tap') ? 'dotknij celu lub wybierz Anuluj' : 'wybierz cel (Esc, aby anulować)';
    return `Rzuć zaklęcie ${translate(targeting[1])}: ${verb}`;
  }

  const reward = text.match(/^Reward: \*\*(.+?) gold\*\*, alive\. The goose also alive, please\.$/);
  if (reward) return `Nagroda: **${reward[1]} sztuk złota**, żywy. Gęś też, jeśli można.`;

  const day = text.match(/^You are on day ([IVXLCDM]+) of Commission ([IVXLCDM]+)\.$/);
  if (day) return `Jesteś w dniu ${day[1]} misji ${day[2]}.`;

  const lost = text.match(/^Commission ([IVXLCDM]+) was lost on day ([IVXLCDM]+)\.$/);
  if (lost) return `Misja ${lost[1]} zakończyła się porażką w dniu ${lost[2]}.`;

  const complete = text.match(/^Commission ([IVXLCDM]+) is complete, and the King is waiting for you at court\.$/);
  if (complete) return `Misja ${complete[1]} jest zakończona. Król czeka na ciebie na dworze.`;

  const dismiss = text.match(/^Send the (.+) home for good\?$/);
  if (dismiss) return `Odesłać oddział ${dismiss[1]} na zawsze?`;

  const order = text.match(/^DAY\s+(.+)$/);
  if (order) return `DZIEŃ  ${order[1]}`;

  const bounty = text.match(/^(?:BOUNTY:|Bounty:)\s*(.*)$/);
  if (bounty) return `NAGRODA: ${translate(bounty[1])}`;

  return text
    .replace(/(\d[\d,]*)\s+(Peasants|Peasant|Archers|Archer|Knights|Knight|Swordsmen|Swordsman|Crossbowmen|Crossbowman|Wolves|Wolf|Goblins|Goblin|Trolls|Troll|Bears|Bear|Boars|Boar|Spiders|Spider|Cutpurses|Bandits|Poachers|Huntsmen|Pikemen|Men-at-arms)\b/g, (_match, count: string, name: string) => `${count} ${translate(name)}`)
    .replace(/(\d[\d,]*)\s+gold\b/g, '$1 sztuk złota')
    .replace(/\band (?=\d[\d,]*\s)/g, 'i ');
}
